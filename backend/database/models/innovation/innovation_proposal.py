# backend/database/models/innovation/innovation_proposal.py

from datetime import datetime
from typing import Optional, Dict, Any

class InnovationProposal:
    """
    Represents an innovation proposal in the database.

    This model stores all information related to a proposal generated by the
    Autonomous Innovation Engine, from its initial concept to its approval status.
    """
    def __init__(
        self,
        title: str,
        description: str,
        opportunity_details: Dict[str, Any],
        proposal_id: Optional[str] = None,
        status: str = "pending_review",
        created_at: Optional[datetime] = None,
        updated_at: Optional[datetime] = None
    ):
        """
        Initializes an InnovationProposal instance.

        Args:
            proposal_id (Optional[str]): The unique identifier for the proposal.
            title (str): The title of the proposal.
            description (str): A detailed description of the innovation.
            opportunity_details (Dict[str, Any]): Data backing the opportunity.
            status (str): The current status (e.g., pending_review, approved, rejected).
            created_at (Optional[datetime]): Timestamp of creation.
            updated_at (Optional[datetime]): Timestamp of last update.
        """
        self.proposal_id = proposal_id
        self.title = title
        self.description = description
        self.opportunity_details = opportunity_details
        self.status = status
        self.created_at = created_at or datetime.utcnow()
        self.updated_at = updated_at or datetime.utcnow()

    def to_dict(self) -> Dict[str, Any]:
        """Serializes the proposal object to a dictionary."""
        return {
            "proposal_id": self.proposal_id,
            "title": self.title,
            "description": self.description,
            "opportunity_details": self.opportunity_details,
            "status": self.status,
            "created_at": self.created_at.isoformat(),
            "updated_at": self.updated_at.isoformat(),
        }
